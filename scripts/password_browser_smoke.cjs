// Isolated writing_test only. Public registration/login are exercised without
// injected cookies. The legacy fixture cookie is used only for migration setup.
const { chromium } = require('/app/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const folder = process.env.B1_FIXTURE_DIR;
  const fixture = JSON.parse(fs.readFileSync(folder + '/session.json', 'utf8'));
  const origin = 'http://localhost:3200';
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + '/workspace');
  await page.getByRole('button', {name:'没有账号，去注册'}).click();
  await page.getByLabel('邮箱', {exact:true}).fill(fixture.registration_email);
  await page.getByLabel('密码', {exact:true}).fill('browser-test-password');
  await page.getByLabel('再次输入密码', {exact:true}).fill('browser-test-password');
  await page.screenshot({path:'/materials/docs/design/password-register-desktop.png',fullPage:true});
  await page.getByRole('button', {name:'注册并进入',exact:true}).click();
  await page.getByLabel('笔名', {exact:true}).fill('自主注册验收');
  await page.getByRole('button', {name:'保存笔名',exact:true}).click();
  const me = await (await context.request.get(origin + '/api/me')).json();
  assert.notEqual(me.id, fixture.owner);
  await page.getByRole('button', {name:'新建草稿',exact:true}).click();
  await page.getByLabel('草稿标题', {exact:true}).fill('自主注册测试');
  await page.getByLabel('草稿正文', {exact:true}).fill('注册后正常写作，邮件服务不参与这条链路。');
  await page.getByRole('status').filter({hasText:/^已保存$/}).waitFor();
  await page.getByRole('button', {name:'退出登录',exact:true}).click();
  await page.getByLabel('邮箱', {exact:true}).fill(fixture.registration_email);
  await page.getByLabel('密码', {exact:true}).fill('browser-test-password');
  await page.getByRole('button', {name:'登录',exact:true}).click();
  await page.locator('.draft-sidebar .draft-item').filter({hasText:'自主注册测试'}).click();
  assert.equal(await page.getByLabel('草稿正文',{exact:true}).inputValue(),'注册后正常写作，邮件服务不参与这条链路。');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'退出登录',exact:true}).click();
  await page.getByRole('button',{name:'没有账号，去注册'}).waitFor();
  await page.screenshot({path:'/materials/docs/design/password-login-mobile.png',fullPage:true});
  assert.equal(await page.getByRole('button',{name:'获取验证码'}).count(),0);
  const legacy = await browser.newContext();
  await legacy.addCookies([{name:'tako_session',value:fixture.token,url:origin,httpOnly:true,sameSite:'Lax'}]);
  const settings = await legacy.newPage();
  await settings.goto(origin + '/account');
  await settings.getByLabel('密码（至少 8 个字符）').fill('legacy-browser-password');
  await settings.getByLabel('再次输入密码').fill('legacy-browser-password');
  await settings.getByRole('button',{name:'设置密码',exact:true}).click();
  await settings.getByRole('status').filter({hasText:'密码已设置'}).waitFor();
  const login = await context.request.post(origin+'/api/auth/login',{data:{email:fixture.owner+'@example.test',password:'legacy-browser-password'},headers:{Origin:origin}});
  assert.equal(login.status(),200);assert.equal((await login.json()).id,fixture.owner);
  const blocked=await context.request.post(origin+'/api/auth/verify',{data:{email:fixture.registration_email,code:'123456'},headers:{Origin:origin}});
  assert.equal(blocked.status(),403);
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: public password registration -> nickname -> saved draft -> logout/login preserved text; legacy self-setup preserved ID; mobile has no OTP; OTP blocked. No mail sent.');
})().catch(error=>{console.error(error.message);process.exit(1)});
